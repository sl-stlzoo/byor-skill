#!/usr/bin/env python3
"""Export the public interview question bank as a static browser asset."""
import argparse
import csv
import io
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]

TEMPLATE_COLUMNS = [
    "row_type", "domain", "domain_name", "name", "ring", "quadrant", "isNew", "status",
    "description", "owner", "confidence", "evidence", "last_reviewed", "next_review",
    "decision_notes", "tool_id", "previous_ring", "ring_reason", "radial", "champion",
    "also_in", "next_action",
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the browser question bank is stale")
    args = parser.parse_args()

    def config(name):
        return yaml.safe_load((ROOT / "config" / f"{name}.yaml").read_text(encoding="utf-8"))

    schemes = config("quadrants")["schemes"]
    project = json.loads((ROOT / "project.json").read_text(encoding="utf-8"))
    bank = {
        "instructions": "https://raw.githubusercontent.com/{owner}/{repo}/{branch}/AGENTS.md".format(**project),
        "domains": [{key: value for key, value in domain.items() if key in {
            "id", "name", "quadrant", "scope", "clarify", "clarify_options", "probes"}}
                    for domain in config("domains")["domains"]],
        "groups": schemes["business-domains"]["quadrants"],
        "quadrants": [q["name"] for q in schemes["thoughtworks-classic"]["quadrants"]],
        "rings": config("rings")["rings"],
    }
    data = "// Generated by scripts/build_interview.py; edit config/ instead.\n"
    data += "const interviewQuestions = " + json.dumps(bank, ensure_ascii=True, indent=2) + ";\n"
    example = {
        "row_type": "EXAMPLE", "domain": "accounting", "domain_name": "Accounting General Ledger",
        "name": "EXAMPLE - Sample Ledger", "ring": "Trial", "quadrant": "Tools", "isNew": "FALSE",
        "status": "Moved In", "description": "EXAMPLE ONLY: A fictional ledger is being tested on real work. "
        "The team will review its fit before deciding whether to expand use.",
        "owner": "Finance lead (example role)", "confidence": "medium", "evidence": "user-stated",
        "last_reviewed": "2026-01-15", "next_review": "2026-07-15",
        "decision_notes": "Example pilot; confirm the ring.", "tool_id": "x-example-sample-ledger",
        "previous_ring": "Assess", "ring_reason": "Example pilot began.", "radial": "0.5",
        "champion": "Finance team (example role)", "also_in": "budgeting",
        "next_action": "Review the example pilot.",
    }
    buffer = io.StringIO(newline="")
    writer = csv.DictWriter(buffer, fieldnames=TEMPLATE_COLUMNS, lineterminator="\n")
    writer.writeheader()
    writer.writerow(example)
    for domain in bank["domains"]:
        writer.writerow({"row_type": "AREA", "domain": domain["id"], "domain_name": domain["name"]})
    outputs = {ROOT / "interview-questions.js": data, ROOT / "templates" / "byor-blank.csv": buffer.getvalue()}
    if args.check:
        for target, expected in outputs.items():
            if not target.exists() or target.read_text(encoding="utf-8") != expected:
                parser.exit(1, f"{target.name} is stale; run python scripts/build_interview.py.\n")
    else:
        for target, content in outputs.items():
            target.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
